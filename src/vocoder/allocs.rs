/// Maximum bit allocation for any B_m at each harmonic count L.
///
/// `MAX_BITS[l]` is the maximum value in `BITS[l]`, i.e. the largest number
/// of bits allocated to any single amplitude for harmonic count L = l + MIN_HARMONICS.
static MAX_BITS: [u8; NUM_HARMONICS] = [
    10, 9, 9, 8, 7, 7, 7, 6, 6, 6,
     6, 6, 5, 5, 5, 5, 5, 5, 5, 4,
     4, 4, 4, 4, 4, 4, 4, 4, 4, 4,
     4, 4, 4, 4, 4, 4, 4, 3, 3, 3,
     3, 3, 3, 3, 3, 3, 3, 3,
];

#[cfg(test)]
mod tests {
    use super::*;
    use crate::vocoder::consts::MIN_HARMONICS;

    #[test]
    fn max_bits_matches_row_maxima() {
        for (row, &expected_max) in BITS.iter().zip(MAX_BITS.iter()) {
            let actual_max = *row.iter().max().unwrap_or(&0);
            assert_eq!(actual_max, expected_max);
        }
    }

    #[test]
    fn allocations_for_13_harmonics() {
        let (bits, max) = allocations(13);
        assert_eq!(
            &bits[..12],
            &[7, 7, 7, 6, 6, 7, 7, 6, 5, 4, 3, 3]
        );
        assert!(bits[12..].iter().all(|&b| b == 0));
        assert_eq!(max, 7);
    }

    #[test]
    fn allocations_for_33_harmonics() {
        let (bits, max) = allocations(33);
        assert_eq!(
            &bits[..32],
            &[4, 3, 3, 3, 3, 3, 3, 2, 2, 3, 3, 2, 2, 3, 2, 1,
              1, 2, 2, 1, 1, 1, 2, 1, 1, 1, 1, 2, 1, 1, 1, 1]
        );
        assert!(bits[32..].iter().all(|&b| b == 0));
        assert_eq!(max, 4);
    }

    #[test]
    fn allocations_for_min_harmonics() {
        let (bits, max) = allocations(MIN_HARMONICS as u32);
        assert_eq!(&bits[..8], &[10, 9, 9, 9, 9, 9, 8, 7]);
        assert!(bits[8..].iter().all(|&b| b == 0));
        assert_eq!(max, 10);
    }

    #[test]
    fn allocations_for_max_harmonics() {
        let (bits, max) = allocations(56);
        // Last row — should have non-zero entries up to index 50
        assert_eq!(bits[0], 3);
        assert_eq!(max, 3);
    }

    #[test]
    fn table_dimensions_are_correct() {
        assert_eq!(BITS.len(), NUM_HARMONICS);
        assert_eq!(MAX_BITS.len(), NUM_HARMONICS);
        for row in &BITS {
            assert_eq!(row.len(), MAX_QUANTIZED_AMPLITUDES);
        }
    }
}
