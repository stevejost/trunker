//! Bit allocation tables for quantized spectral amplitudes.
//!
//! These tables (Annex F and Annex G of TIA-102.BABA) define how many bits
//! are allocated to each quantized amplitude B_m for a given harmonic count L.

use super::consts::{MAX_QUANTIZED_AMPLITUDES, MIN_HARMONICS, NUM_HARMONICS};

/// Retrieve the bit allocations B_m and max(B_m) for the given harmonic count L.
///
/// Returns a tuple of:
/// - A slice of `MAX_QUANTIZED_AMPLITUDES` entries, where entry `k` is the bit
///   allocation B_(3+k) for harmonic count L. Unused entries are 0.
/// - The maximum bit allocation across all entries for this L.
///
/// # Panics
///
/// Panics if `harmonic_count` is outside the valid range (9..=56).
pub fn allocations(harmonic_count: u32) -> (&'static [u8], u8) {
    let index = harmonic_count as usize - MIN_HARMONICS;
    (&BITS[index][..], MAX_BITS[index])
}

